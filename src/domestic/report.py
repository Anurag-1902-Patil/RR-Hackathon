"""Uncapped Indian fresher picks: CSVs, figure and the combined final submission list.

Outputs
- reports/top_5_uncapped_batters.csv, reports/top_5_uncapped_bowlers.csv
- reports/figures/report/uncapped_picks.png
- reports/FINAL_SUBMISSION_LIST.csv and reports/FINAL_SUBMISSION.md (all 30 names, one place)
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from src.config import REPORTS_DIR  # noqa: E402
from src.domestic.verified_uncapped import DISPLAY  # noqa: E402

MO = REPORTS_DIR / "model_outputs"
PURPLE, PINK, GREY = "#4B2A99", "#C2185B", "#8A8AA0"
N = 5


def picks(side: str) -> pd.DataFrame:
    y = pd.read_csv(MO / f"uncapped_scores_{side}.csv")
    p = y[y.in_pool].sort_values("pool_rank").head(N).copy()
    hb = "balls_high" if side == "batting" else "legal_balls_high"
    out = pd.DataFrame({
        "rank": p.pool_rank.astype(int), "player": p.cricsheet_name.map(DISPLAY).fillna(p.full_name), "full_name": p.full_name, "scorecard_name": p.cricsheet_name, "domestic_team": p.smat_team,
        "age_at_auction": p.age_at_auction.astype(int), "role": p.role, "reliability_score": p.score.round(1),
        "p_top5_bootstrap": p.get("p_top5", pd.Series(index=p.index, dtype=float)).round(2),
        "boot_rank_p05": p.get("boot_rank_p05"), "boot_rank_p95": p.get("boot_rank_p95"),
        "high_pressure_balls_smat": p[hb].astype(int), "pressure_innings_smat": p.pressure_innings.astype(int),
        "value_per100_high": p.value_per100_high.round(1),
        "smat_seasons": p.smat_seasons, "last_smat_match": p.last_smat_match,
        "status": "Uncapped Indian, not on any IPL 2026 squad, aged <=30 at auction (verified 2026-11-14)",
        "confidence": "Moderate (SMAT batting predicts IPL batting, Spearman 0.50)" if side == "batting"
        else "Low (SMAT bowling did not predict IPL bowling, Spearman ~0): watchlist",
    })
    if side == "batting":
        out.insert(13, "sr_high", p.sr_high.round(1)); out.insert(14, "sr_low", p.sr_low.round(1))
    else:
        out.insert(13, "economy_high", p.economy_high.round(2)); out.insert(14, "economy_low", p.economy_low.round(2))
        out.insert(15, "wickets_high", p.wickets_high.astype(int))
    return out


def figure(b: pd.DataFrame, w: pd.DataFrame) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.2))
    for ax, t, title, col in ((axes[0], b, "Uncapped fresher batters", PURPLE), (axes[1], w, "Uncapped fresher bowlers (low confidence)", PINK)):
        t = t.iloc[::-1]
        ax.barh(t.player, t.reliability_score, color=col, height=0.55)
        for i, (s, p) in enumerate(zip(t.reliability_score, t.p_top5_bootstrap)):
            ax.text(s + 1, i, f"{s:.0f}" + (f"  ·  P(top 5) {p:.0%}" if pd.notna(p) else ""), va="center", fontsize=9, color="#222")
        ax.set_xlim(0, 115); ax.set_title(title, fontsize=12, loc="left")
        ax.set_xlabel("Reliability score (percentile among all eligible SMAT players)")
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
        ax.tick_params(axis="y", labelsize=10)
    fig.tight_layout()
    out = REPORTS_DIR / "figures" / "report" / "uncapped_picks.png"
    fig.savefig(out, dpi=200); plt.close(fig)


def submission(b: pd.DataFrame, w: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for cat, f in (("Top 10 batters RR can sign", "top_10_batsmen.csv"), ("Top 10 bowlers RR can sign", "top_10_bowlers.csv")):
        t = pd.read_csv(REPORTS_DIR / f)
        rows += [{"category": cat, "rank": int(r["rank"]), "player": r.player, "country": r.national_side, "role": r.role,
                  "reliability_score": round(r.score, 1), "p_top": round(r.p_top10, 2), "evidence": "IPL + T20I 2022-26 (RR data pack)"} for _, r in t.iterrows()]
    for cat, t in (("Uncapped Indian fresher batters", b), ("Uncapped Indian fresher bowlers (watchlist)", w)):
        rows += [{"category": cat, "rank": int(r["rank"]), "player": r.player, "country": "India (uncapped)", "role": r.role,
                  "reliability_score": r.reliability_score, "p_top": r.p_top5_bootstrap,
                  "evidence": f"Syed Mushtaq Ali Trophy {r.smat_seasons} (Cricsheet)"} for _, r in t.iterrows()]
    s = pd.DataFrame(rows)
    s.to_csv(REPORTS_DIR / "FINAL_SUBMISSION_LIST.csv", index=False)
    md = ["# SupeRR Selector Season 2: Final Submission List", "",
          "Generated by `src/domestic/report.py` from the pipeline outputs (information cut-off 14 Nov 2026).", "",
          "**Round 1 answer:** the 10 most reliable batters and 10 most reliable bowlers under pressure that Rajasthan Royals can sign at the "
          "IPL 2027 auction, plus 5 + 5 uncapped Indian freshers rated on domestic T20 pressure performance.", ""]
    for cat in s.category.unique():
        t = s[s.category == cat]
        top = "P(top 10)" if "Top 10" in cat else "P(top 5)"
        md += [f"## {cat}", "", f"| # | Player | Country | Role | Score | {top} | Evidence |", "|---:|---|---|---|---:|---:|---|"]
        md += [f"| {r['rank']} | {r.player} | {r.country} | {r.role} | {r.reliability_score:.0f} | "
               f"{'' if pd.isna(r.p_top) else f'{r.p_top:.0%}'} | {r.evidence} |" for _, r in t.iterrows()]
        md.append("")
    md += ["## Read with", "",
           "- Scores are percentiles among all eligible players in the relevant data (international/IPL or SMAT), not directly comparable across the two groups.",
           "- Uncapped batting evidence is moderately predictive of IPL batting (Spearman 0.50 over 26 players who played both); uncapped bowling evidence is not (about 0), so the bowling five are a watchlist.",
           "- Cricsheet SMAT data runs to 2024/25 (8 matches that season); most fresher evidence is 2020/21 to 2023/24.",
           "", "## Submission files", "",
           "- **Deck (10 slides):** `reports/SupeRR_Intelligence_Pitch.pptx`",
           "- **Dashboard (single HTML file, opens offline in any browser):** `dashboard/SupeRR_Intelligence_Dashboard.html`",
           "- **Pitch video:** `reports/video/SupeRR_Intelligence_Pitch.mp4`",
           "- Supporting detail (not part of the submission): full report, 27-slide technical deck and Streamlit app in the repository.", ""]
    (REPORTS_DIR / "FINAL_SUBMISSION.md").write_text("\n".join(md), encoding="utf-8")
    return s


def run() -> None:
    b, w = picks("batting"), picks("bowling")
    b.to_csv(REPORTS_DIR / "top_5_uncapped_batters.csv", index=False)
    w.to_csv(REPORTS_DIR / "top_5_uncapped_bowlers.csv", index=False)
    figure(b, w)
    submission(b, w)
    print(b[["rank", "player", "age_at_auction", "reliability_score", "p_top5_bootstrap"]].to_string(index=False))
    print(w[["rank", "player", "age_at_auction", "reliability_score", "p_top5_bootstrap"]].to_string(index=False))


if __name__ == "__main__":
    run()
